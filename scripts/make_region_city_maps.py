TEMPLATE = """\
# GENERATED by scripts/make_region_city_maps.py — edit the generator, not this file.
# colored-geostats regional city heat map {number}: {name}.
# Every city of 100,000+ people in the region as a dot, on the spectral heat scale:
#   dot area   → city population
#   dot colour → city density: dark blue (lowest) → sky blue → green (region average,
#                log scale) → yellow → orange → red (≥ overpopulated threshold)
# Between the dots: population density of suburbs and countryside (GHSL 2025 grid) —
#   grey below 10 people/km², then blue → red, red at 2,000 people/km² and above.
# {note}

parameters:
  min_city_population: "${{CITY_MIN_POPULATION:-100000}}"
  overpopulated_per_km2: &overpopulated_per_km2 "${{CITY_OVERPOPULATED_PER_KM2:-10000}}"

metadata:
  slug: {slug}
  title: "Region {number} — {name}: Cities, Population & Density"
  category: colored-geostats
  license: "CC0 (Wikidata); CC BY 4.0 (World Bank WDI); map geometry public domain (Natural Earth)"
  update_frequency: monthly
  attribution: &attribution "Cities: Wikidata (population, area, coordinates) · Country names: World Bank WDI"

schema:
  - {{ name: wikidata_id,              dtype: str }}
  - {{ name: city,                     dtype: str }}
  - {{ name: iso3,                     dtype: str }}
  - {{ name: country,                  dtype: str,   nullable: true }}
  - {{ name: latitude,                 dtype: float }}
  - {{ name: longitude,                dtype: float }}
  - {{ name: population,               dtype: int }}
  - {{ name: area_km2,                 dtype: float, nullable: true }}
  - {{ name: density_per_km2,          dtype: float, unit: "people/km2", nullable: true, description: "population / area; cities with a missing or implausible area are excluded" }}
  - {{ name: overpopulated,            dtype: bool,  nullable: true, description: "density_per_km2 >= parameters.overpopulated_per_km2" }}

sources:
  - type: sparql
    strip_uri_prefix: true
    query: |
      SELECT ?city ?cityLabel ?iso3 ?population ?latitude ?longitude ?area_km2
      WHERE {{
        {{
          SELECT ?city (SAMPLE(?iso) AS ?iso3) (MAX(?pop) AS ?population)
                 (SAMPLE(?lat) AS ?latitude) (SAMPLE(?lon) AS ?longitude)
                 (MAX(?areaM2) / 1000000 AS ?area_km2)
          WHERE {{
            ?city wdt:P31/wdt:P279* wd:Q515 ;
                  wdt:P1082 ?pop ;
                  wdt:P17/wdt:P298 ?iso ;
                  p:P625/psv:P625 [ wikibase:geoLatitude ?lat ; wikibase:geoLongitude ?lon ] .
            FILTER(?iso IN ({query_codes}))
{extra_filter}            OPTIONAL {{ ?city p:P2046/psn:P2046/wikibase:quantityAmount ?areaM2 . }}
          }}
          GROUP BY ?city
          HAVING (MAX(?pop) >= ${{CITY_MIN_POPULATION:-100000}})
        }}
        SERVICE wikibase:label {{ bd:serviceParam wikibase:language "en,mul". }}
      }}
  - type: worldbank-latest
    indicators:
      SP.POP.TOTL.FE.ZS: {{ value: female_share_pct }}
    most_recent_non_empty: true
    exclude_aggregates: true

processing:
  - rename: {{ columns: {{ city: wikidata_id, cityLabel: city }} }}
  - lookup:
      from_source: worldbank-latest
      "on": iso3
      columns: {{ country: country }}
  - normalize
  - derive: {{ column: density_per_km2, expr: "ratio(population, area_km2)" }}
  # Wikidata areas are crowd-sourced; a wrong unit gives impossible densities. Null them.
  - derive: {{ column: density_per_km2, expr: "null_outside(density_per_km2)", params: {{ low: 10, high: 60000 }} }}
  - filter: {{ when: {{ column: density_per_km2, not_null: true }}, reason: "no usable density (missing or implausible area)" }}
  - derive: {{ column: overpopulated,   expr: "at_least(density_per_km2)", params: {{ threshold: *overpopulated_per_km2 }} }}
  - derive: {{ column: density_per_km2, expr: "round_to(density_per_km2, digits=1)" }}
  - derive: {{ column: area_km2,        expr: "round_to(area_km2, digits=2)" }}
  - derive: {{ column: latitude,        expr: "round_to(latitude, digits=4)" }}
  - derive: {{ column: longitude,       expr: "round_to(longitude, digits=4)" }}
  - sort: {{ by: [iso3, city, wikidata_id] }}
  - validate

outputs:
  - csv
  - svg-dot-map:
      geometry: natural-earth-admin0-110m
      scope: region
      region: {{ iso3: [{map_codes}] }}
{clip}      latitude_column: latitude
      longitude_column: longitude
      size_column: population
      size_label: city population
      name_column: city
      item_label: cities
      label_columns: [country, population, density_per_km2, overpopulated]
      min_radius: 1.2
      max_radius: 16
      title: "Region {number} — {name}: cities of 100,000+, population & density"
      footer: *attribution
      background: "#f3f6f9"
      basemap_color: "#d5d9de"
      border_color: "#ffffff"
      dot_stroke: "#ffffff"
      density_surface:                         # population density between the cities (GHSL 2025)
        low: 10                                  # below: grey basemap
        high: 2000                               # blue → red up to here, red above
      color_scale:
        type: spectral-density
        value_column: density_per_km2
        value_label: "City density (people/km², log scale)"
        normalize: log
        center: mean                             # green = average of the region's cities
        saturate_above: *overpopulated_per_km2   # red = overpopulated and above
"""


def render(region: Region) -> str:
    extra = ""
    if region.russia_west_of is not None:
        extra = (f'            # Russia only up to the Urals.\n'
                 f'            FILTER(?iso != "RUS" || ?lon <= {region.russia_west_of})\n')
    clip = f"      clip_bbox: [{', '.join(f'{v:g}' for v in region.clip_bbox)}]\n" if region.clip_bbox else ""
    return TEMPLATE.format(
        number=region.number, name=region.name, note=region.note, slug=slug_of(region),
        query_codes=", ".join(f'"{code}"' for code in region.query),
        extra_filter=extra, map_codes=", ".join(region.map), clip=clip,
    )


def slug_of(region: Region) -> str:
    return f"cities-heat-r{region.number}-{region.slug}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any generated file is missing or stale")
    args = parser.parse_args(argv)
    stale = []
    for region in REGIONS:
        path = DATASETS / slug_of(region) / "dataset.yaml"
        text = render(region)
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(DATASETS.parent)}")
    if stale:
        print("stale or missing (re-run without --check):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Generate the nine regional city heat-map datasets from one region table.

Each region becomes its own dataset (``datasets/cities-heat-rN-<name>/``) so that
its Wikidata query fetches only that region's cities and its map legend counts
("Cities shown: N of M") refer to the region, not the world. The datasets are
identical except for the region definition below, so they are generated rather
than hand-copied: edit REGIONS or TEMPLATE here, then re-run

    python scripts/make_region_city_maps.py          # write the YAML files
    python scripts/make_region_city_maps.py --check  # fail if any file is stale

Two code lists per region: ``query`` holds ISO 3166 alpha-3 codes as Wikidata
stores them; ``map`` holds the Natural Earth ADM0_A3 keys of the basemap, which
differ for a few territories (SSD→SDS, PSE→PSX, XKX→KOS, ESH→SAH, plus the
de-facto entities SOL Somaliland and CYN Northern Cyprus). Countries too small
for the 110m basemap (Singapore, Bahrain, Malta …) still get their city dots.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path

